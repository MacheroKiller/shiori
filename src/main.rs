mod clients;
mod database;
mod models;
mod provider;
mod repositories;
mod services;

use crate::{
    clients::{
        anilist_client::AniListClient, http_client::HttpClient, telegram_client::TelegramClient,
    },
    database::connection::create_pool,
    repositories::{
        notification_repository::NotificationRepository, release_repository::ReleaseRepository,
        season_repository::SeasonRepository,
    },
    services::{
        anilist_service::AniListService, notification_worker::TelegramWorker,
        release_sync_service::ReleaseSyncService, telegram_service::TelegramService,
    },
};

use std::{error::Error, sync::Arc};
use tokio::time::{Duration, MissedTickBehavior, interval};

#[tokio::main]
async fn main() -> Result<(), Box<dyn Error + Send + Sync>> {
    dotenvy::dotenv().ok();

    // Load environment variables
    let database_url = dotenvy::var("DATABASE_URL")?;
    let telegram_bot_token = dotenvy::var("TELEGRAM_BOT_TOKEN")?;
    let telegram_chat_id = dotenvy::var("TELEGRAM_CHAT_ID")?;
    let telegram_animelist_thread_id =
        dotenvy::var("TELEGRAM_ANIMELIST_THREAD_ID")?.parse::<u64>()?;

    // Initialize database
    let pool = create_pool(&database_url).await?;

    // Initialize HTTP client
    let http_client = Arc::new(HttpClient::new());

    // Initialize API clients
    let anilist_client = AniListClient::new(Arc::clone(&http_client));
    let telegram_client = TelegramClient::new(Arc::clone(&http_client), telegram_bot_token);

    // Initialize services
    let anilist_service = AniListService::new(anilist_client);

    let telegram_service = TelegramService::new(
        telegram_client,
        telegram_chat_id,
        telegram_animelist_thread_id,
    );

    // Initialize repositories
    let season_repository = SeasonRepository::new(pool.clone());
    let notification_repository = NotificationRepository::new(pool.clone());

    let release_repository = ReleaseRepository::new(
        pool.clone(),
        season_repository,
        notification_repository.clone(),
    );

    // Initialize synchronization service
    let release_sync_service =
        ReleaseSyncService::new(Box::new(anilist_service), release_repository);

    // Initialize notification worker
    let telegram_worker = TelegramWorker::new(notification_repository, telegram_service);

    // Configure execution intervals
    let mut sync_interval = interval(Duration::from_secs(6 * 60 * 60));
    let mut notification_interval = interval(Duration::from_secs(30));

    sync_interval.set_missed_tick_behavior(MissedTickBehavior::Skip);
    notification_interval.set_missed_tick_behavior(MissedTickBehavior::Skip);

    println!("Release Tracker started!");
    println!("AniList synchronization: every 6 hours");
    println!("Notification processing: every 30 seconds");

    // Main execution loop
    loop {
        tokio::select! {
            // Synchronize releases every 6 hours
            _ = sync_interval.tick() => {
                println!("\nStarting AniList synchronization...");

                match release_sync_service.sync().await {
                    Ok(result) => {
                        println!("Release synchronization completed!");

                        println!("Total received: {}", result.summary.total_received);
                        println!("Inserted: {}", result.summary.inserted);
                        println!("Updated: {}", result.summary.updated);
                        println!("Unchanged: {}", result.summary.unchanged);
                        println!("Events generated: {}", result.events.len());
                    }

                    Err(error) => {
                        eprintln!("AniList synchronization failed: {}", error);
                    }
                }

                // Process notifications generated by synchronization
                if let Err(error) = telegram_worker.process_pending().await {
                    eprintln!("Notification processing failed: {}", error);
                }
            }

            // Process pending notifications every 30 seconds
            _ = notification_interval.tick() => {
                if let Err(error) = telegram_worker.process_pending().await {
                    eprintln!("Notification processing failed: {}", error);
                }
            }
        }
    }
}
